/** Text for `key` in `lang`, with {name} placeholders filled. Falls back to English, then to the key, so a gap is visible rather than blank. */
export function t(lang, key, vars = {}) {
  const pick = (l) => key.split('.').reduce((o, k) => (o == null ? undefined : o[k]), TEXT[l]);
  let s = pick(lang) ?? pick('en') ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}
