"""
T-W1 -- Build and validate the watchlist (docs/IMPLEMENTATION_PLAN.md Phase 1;
docs/CHENNAI_PROTOTYPE_SPEC.md section 4; docs/DECISIONS.md ADR-009).

**What this script does, and does not, complete.** T-W1's full acceptance criterion is a
resident-reviewed map ("a Chennai resident looks at and says 'yes, those are the places'"),
with basin labels sourced from a real GIS join and each point "named as a resident would say
it." Those two steps are explicitly NOT automatable from data on this machine (the plan's own
words: "this is a manual/GIS join, not yet automatable, since no basin-boundary shapefile was
found") and are not attempted here. What this script DOES do, end to end, from data already on
disk (no new downloads, no paid services, per CLAUDE.md's Rule 1):

  1. Parse the real OpenCity/GCC flood-hazard-zone KML (T0.5's confirmed data source; GO
     decision already recorded in data/results/2026-09-12-t05-watchlist/).
  2. Filter to the High/Very High risk categories (the two most policy-relevant tiers) --
     1,504 of 7,453 zones -- since T-W1's 150-200-point target implies real chronic points,
     not every hazard-hinted polygon at every risk level.
  3. Cluster adjacent zone centroids (many are fragments of the same real flooded stretch,
     not independent points) using the same 150 m radius ADR-010 already uses for report
     coarsening, for consistency rather than a fresh arbitrary number.
  4. Score each cluster's proximity to the Michaung (4 Dec 2023) press-sourced leads named in
     research/SYNTHESIS.md section 9's addendum and docs/CHENNAI_PROTOTYPE_SPEC.md section 4
     -- a cluster near BOTH the 2026 GCC hazard-zone data and a 2023 real-flood press report is
     the two-source cross-check ADR-009/T-W1 ask for.
  5. Snap each cluster centroid to the nearest drivable OSM way, using
     data/osm/chennai_overpass_drivable.json (generated by
     scripts/fetch_chennai_drivable_ways.py -- see that script's own docstring; it carries full
     way geometry, unlike chennai_graph.sqlite, which T0.2 built purely for Dijkstra timing and
     stripped of coordinates entirely). **This is a live Overpass snapshot, not a pinned one**
     (same caveat T0.2 already states about itself) -- every way_id produced here is
     provisional and will likely need re-resolution once T1.3's real graph build exists,
     against the pinned Geofabrik extract.
  6. Emit a coarse, EXPLICITLY-FLAGGED-UNVERIFIED basin label from known basin geography
     (research/SYNTHESIS.md section 9 addendum: Kosasthalaiyar/Cooum/Adyar/Kovalam are real,
     named, roughly-bounded basins, just not available here as a shapefile) -- a starting
     placeholder for the human GIS join, not a substitute for it.

**Caveat on step 4's coordinates**, stated once here rather than buried in a constant: the
Michaung lead localities' coordinates below are approximate locality centroids from general
geographic knowledge, not a geocoding API or surveyed data -- they are good enough for a
multi-kilometre proximity flag, not for edge-level precision. Same caveat, same reason, for
step 6's basin bands.

Usage: .venv/Scripts/python.exe scripts/tw1_build_watchlist.py
"""

