ROOT = Path(__file__).resolve().parent.parent
KML_PATH = ROOT / "data" / "watchlist_raw" / "chennai_flood_hazard_zones.kml"
WAYS_PATH = ROOT / "data" / "osm" / "chennai_overpass_drivable.json"
TODAY = datetime.now(tz=timezone.utc).date().isoformat()
OUT_DIR = ROOT / "data" / "watchlist" / TODAY
RESULTS_DIR = ROOT / "data" / "results" / f"{TODAY}-tw1-watchlist"

NS = {"kml": "http://www.opengis.net/kml/2.2"}

# Cluster radius -- HOW BIG IS "ONE CHRONIC WATERLOGGING POINT" IS NOT A SETTLED QUESTION.
# ADR-010's 150 m grid answers a different question (anonymising a report's location for
# privacy) and does not transfer here just because it's a number this codebase already uses.
# A sensitivity sweep (see this script's docstring and the "cluster_count_by_radius_m" field
# in the written manifest) shows the candidate count is genuinely sensitive to this choice:
# 683 clusters at 150 m, 402 at 300 m, 171 at 750 m (docs/IMPLEMENTATION_PLAN.md's 150-200
# target). 300 m is used as a documented, defensible-but-not-validated default -- large enough
# that adjacent KML polygon fragments of the same road stretch merge, small enough that two
# distinct hazard mechanisms a few hundred metres apart (e.g. two different lakes' overflow
# paths) do not get silently conflated. This is exactly the kind of parameter the resident map
# review (T-W1's actual acceptance test) should validate or override, not something this
# script should quietly pick by tuning until the count "looks right."
CLUSTER_RADIUS_M = 300.0
CLUSTER_RADIUS_SWEEP_M = [150.0, 250.0, 300.0, 400.0, 500.0, 750.0, 1000.0]

HIGH_RISK_CATEGORIES = {"High", "Very High"}

# Grid cell size for the way-geometry spatial index. ~0.01 deg is roughly 1.1 km at Chennai's
# latitude -- coarse enough to keep the index small, fine enough that a candidate point's
# nearest way is almost always in the same or an adjacent cell.
GRID_CELL_DEG = 0.01

# Michaung (4 Dec 2023) press-sourced leads -- research/SYNTHESIS.md section 9 addendum;
# docs/CHENNAI_PROTOTYPE_SPEC.md section 4. Approximate locality centroids, NOT surveyed
# (see this file's top comment). "flooded" localities score a positive proximity signal;
# "not_badly_hit" is the addendum's explicit negative signal (Adyar/Kotturpuram proper were
# reported as NOT badly hit the same day -- a candidate near only these should not inherit
# the corridor's general flood reputation for free).
MICHAUNG_LEADS = {
    "Pallikaranai (200 ft radial road / Narayanapuram Lake overflow)": (
        12.9351,
        80.1988,
        "flooded",
    ),
    "Mudichur / Varadharajapuram / Old Perungalathur / Bharathy Nagar": (
        12.8800,
        80.1180,
        "flooded",
    ),
    "Velachery / Taramani / Perungudi / Madipakkam": (12.9720, 80.2210, "flooded"),
    "Besant Nagar / Sastri Nagar / Thiruvanmiyur": (12.9920, 80.2630, "flooded"),
    "Adyar / Kotturpuram proper (press: NOT badly hit)": (
        13.0160,
        80.2480,
        "not_badly_hit",
    ),
}
MICHAUNG_MATCH_RADIUS_KM = 2.5

# Coarse basin bands from known basin geography (research/SYNTHESIS.md section 9 addendum;
# docs/CHENNAI_PROTOTYPE_SPEC.md section 4) -- latitude bands only, NOT real watershed
# polygons. Every point labelled this way carries basin_label_confidence: "heuristic_unverified"
# in the output; do not treat this as T-W1's basin-assignment step being done.
#
# **Known failure mode, not just imprecision (flagged by independent review):** basins are
# distinguished by which river a point actually drains toward, not by how far north/south it
# sits. With no longitude term at all, this heuristic will mislabel any INLAND point south of
# the Adyar/Kovalam boundary latitude as "Kovalam" (a coastal basin) regardless of how far from
# the coast it actually is -- the mechanism is wrong, not merely coarse. It happens not to
# visibly bite in the current output (the few "Kovalam" points are all near a coastal
# longitude), but nothing here prevents it from doing so on a different candidate set.
BASIN_BANDS = [
    # (min_lat_exclusive, label)  -- evaluated top to bottom, first match wins.
    (13.10, "Kosasthalaiyar"),
    (13.02, "Cooum"),
    (12.90, "Adyar"),
    (float("-inf"), "Kovalam"),
]


def haversine_m(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    r = 6371000.0
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dphi = math.radians(lat2 - lat1)
    dlambda = math.radians(lon2 - lon1)
    a = (
        math.sin(dphi / 2) ** 2
        + math.cos(p1) * math.cos(p2) * math.sin(dlambda / 2) ** 2
    )
    return 2 * r * math.asin(math.sqrt(a))


# ---------------------------------------------------------------------------------------
# Step 1-2: flood hazard zones
# ---------------------------------------------------------------------------------------


def parse_kml_coords(text: str) -> list[tuple[float, float]]:
    pts = []
    for tok in text.split():
        parts = tok.split(",")
        if len(parts) >= 2:
            lon, lat = float(parts[0]), float(parts[1])
            pts.append((lat, lon))
    return pts


def load_flood_zones() -> list[dict]:
    tree = ET.parse(KML_PATH)
    root = tree.getroot()
    zones = []
    for pm in root.findall(".//kml:Placemark", NS):
        fields = {sd.get("name"): sd.text for sd in pm.findall(".//kml:SimpleData", NS)}
        coord_el = pm.find(".//kml:outerBoundaryIs//kml:coordinates", NS)
        if coord_el is None:
            coord_el = pm.find(".//kml:coordinates", NS)
        if coord_el is None or not coord_el.text:
            continue
        pts = parse_kml_coords(coord_el.text)
        if not pts:
            continue
        lat = sum(p[0] for p in pts) / len(pts)
        lon = sum(p[1] for p in pts) / len(pts)
        category = fields.get("CATEGORY")
        area = fields.get("SHAPE.AREA")
        zones.append(
            {
                "objectid": fields.get("OBJECTID"),
                "category": category,
                "shape_area": float(area) if area else 0.0,
                "lat": lat,
                "lon": lon,
            }
        )
    return zones


# ---------------------------------------------------------------------------------------
# Step 3: clustering
# ---------------------------------------------------------------------------------------


def cluster_points(zones: list[dict], radius_m: float) -> list[dict]:
    """Greedy clustering: process zones largest-area-first so a cluster's seed is its most
    prominent member; any later zone within radius_m of an existing cluster's *current*
    centroid joins it (area-weighted running mean), else it starts a new cluster. Not a
    globally optimal clustering, but deterministic, O(n * clusters) which is fine at n=1504,
    and good enough for "these are fragments of the same real place" -- the acceptance bar
    is the resident map review, not this algorithm.
    """
    ordered = sorted(zones, key=lambda z: -z["shape_area"])
    clusters: list[dict] = []
    for z in ordered:
        best = None
        best_dist = radius_m
        for c in clusters:
            d = haversine_m(z["lat"], z["lon"], c["lat"], c["lon"])
            if d <= best_dist:
                best = c
                best_dist = d
        if best is None:
            clusters.append(
                {
                    "lat": z["lat"],
                    "lon": z["lon"],
                    "total_area": z["shape_area"],
                    "member_categories": {z["category"]},
                    "n_members": 1,
                }
            )
        else:
            w_old = best["total_area"]
            w_new = z["shape_area"]
            total = w_old + w_new if (w_old + w_new) > 0 else 1.0
            best["lat"] = (best["lat"] * w_old + z["lat"] * w_new) / total
            best["lon"] = (best["lon"] * w_old + z["lon"] * w_new) / total
            best["total_area"] += z["shape_area"]
            best["member_categories"].add(z["category"])
            best["n_members"] += 1
    return clusters


# ---------------------------------------------------------------------------------------
# Step 4: Michaung proximity scoring
# ---------------------------------------------------------------------------------------


def nearest_michaung_lead(lat: float, lon: float) -> dict | None:
    best_name, best_dist_km, best_status = None, None, None
    for name, (lead_lat, lead_lon, status) in MICHAUNG_LEADS.items():
        d_km = haversine_m(lat, lon, lead_lat, lead_lon) / 1000.0
        if best_dist_km is None or d_km < best_dist_km:
            best_name, best_dist_km, best_status = name, d_km, status
    if best_dist_km is None or best_dist_km > MICHAUNG_MATCH_RADIUS_KM:
        return None
    return {
        "lead": best_name,
        "distance_km": round(best_dist_km, 2),
        "status": best_status,
    }


# ---------------------------------------------------------------------------------------
# Step 5: snap to nearest drivable OSM way
# ---------------------------------------------------------------------------------------


def load_drivable_ways() -> list[dict]:
    """Streams data/osm/chennai_overpass_drivable.json with ijson rather than json.load --
    this is the same 70 MB cached Overpass response T0.2 fetched; streaming keeps this
    script's own memory footprint small and independent of how that file grows, consistent
    with T0.2's documented lesson that this machine has genuinely limited free RAM (as little
    as ~0.4-1.1 GB measured directly), not just a library-choice problem.
    """
    ways = []
    with open(WAYS_PATH, "rb") as f:
        for element in ijson.items(f, "elements.item"):
            if element.get("type") != "way":
                continue
            geometry = element.get("geometry")
            if not geometry:
                continue
            # ijson yields decimal.Decimal for numbers by default; cast to float since
            # every downstream calculation (haversine, grid-cell math) expects it.
            pts = [
                (float(g["lat"]), float(g["lon"]))
                for g in geometry
                if "lat" in g and "lon" in g
            ]
            if len(pts) < 2:
                continue
            tags = element.get("tags", {})
            way_id = element.get("id")
            ways.append(
                {
                    "id": int(way_id) if way_id is not None else None,
                    "highway": tags.get("highway"),
                    "pts": pts,
                    "name": tags.get("name"),
                }
            )
    return ways


def build_grid_index(
    ways: list[dict], cell_deg: float
) -> dict[tuple[int, int], list[int]]:
    index: dict[tuple[int, int], list[int]] = {}
    for i, way in enumerate(ways):
        cells = set()
        for lat, lon in way["pts"]:
            cells.add((int(lat / cell_deg), int(lon / cell_deg)))
        for cell in cells:
            index.setdefault(cell, []).append(i)
    return index


def point_segment_distance_m(
    p: tuple[float, float], a: tuple[float, float], b: tuple[float, float]
) -> float:
    """Approximate point-to-segment distance in metres. Chennai spans <0.5 deg lat/lon, so a
    local equirectangular projection (scaling longitude by cos(latitude)) is accurate to a
    few metres here -- adequate for "which street is this," not for survey-grade geometry.
    """
    lat0 = p[0]
    m_per_deg_lat = 111320.0
    m_per_deg_lon = 111320.0 * math.cos(math.radians(lat0))

    def to_xy(pt: tuple[float, float]) -> tuple[float, float]:
        return (pt[1] * m_per_deg_lon, pt[0] * m_per_deg_lat)

    px, py = to_xy(p)
    ax, ay = to_xy(a)
    bx, by = to_xy(b)
    dx, dy = bx - ax, by - ay
    if dx == 0 and dy == 0:
        return math.hypot(px - ax, py - ay)
    t = ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy)
    t = max(0.0, min(1.0, t))
    cx, cy = ax + t * dx, ay + t * dy
    return math.hypot(px - cx, py - cy)


def snap_to_nearest_way(
    point: tuple[float, float],
    ways: list[dict],
    index: dict[tuple[int, int], list[int]],
    cell_deg: float,
) -> dict | None:
    """Grid-ring nearest-way search.

    **Bug fixed 2026-09-14 (independent review):** the previous version stopped at the first
    non-empty ring and returned the best match found there, without checking whether a *closer*
    way existed one ring further out -- a cell that happens to be in a farther ring can still
    contain a way closer than anything in a nearer ring that just happens to have content. The
    review reproduced this against the real 402-candidate output: 23/402 (5.7%) resolved to a
    different, closer way once this was fixed, including two cases 700-900 m off. The correct
    termination condition is not "the first ring with anything in it" but "no ring further out
    could possibly contain anything closer than what's already been found" -- implemented below
    via a conservative per-ring minimum-distance bound, not a fixed ring count past the first hit.
    """
    lat, lon = point
    cx, cy = int(lat / cell_deg), int(lon / cell_deg)
    # Conservative (i.e. an underestimate, which is the safe direction for a lower bound):
    # metres per degree of longitude shrinks with latitude, and is always <= metres per degree
    # of latitude, so using it for both axes never overstates how close a farther ring could be.
    m_per_deg = 111_320.0 * math.cos(math.radians(lat))

    best_way, best_dist = None, None
    max_radius = (
        60  # ~60 * (cell_deg * m_per_deg) ~= 65 km -- far beyond Chennai's extent
    )
    for radius in range(max_radius + 1):
        # Any cell at this ring is at least (radius - 1) whole cell-widths from the query
        # point, in the worst case where the point sits at the very edge of its own cell.
        ring_min_dist_m = max(0, radius - 1) * cell_deg * m_per_deg
        if best_dist is not None and ring_min_dist_m > best_dist:
            break

        cell_ids: set[int] = set()
        for dx in range(-radius, radius + 1):
            for dy in range(-radius, radius + 1):
                if max(abs(dx), abs(dy)) != radius:
                    continue
                cell_ids.update(index.get((cx + dx, cy + dy), []))

        for i in cell_ids:
            way = ways[i]
            pts = way["pts"]
            for a, b in itertools.pairwise(pts):
                d = point_segment_distance_m(point, a, b)
                if best_dist is None or d < best_dist:
                    best_dist, best_way = d, way

    if best_way is None:
        return None
    return {
        "way_id": best_way["id"],
        "street_name": best_way.get("name"),
        "highway": best_way.get("highway"),
        "distance_m": round(best_dist, 1),
    }


# ---------------------------------------------------------------------------------------
# Step 6: coarse basin heuristic
# ---------------------------------------------------------------------------------------


def distance_stats(distances_m: list[float]) -> dict:
    ds = sorted(distances_m)
    return {
        "min": round(ds[0], 1),
        "median": round(ds[len(ds) // 2], 1),
        "p90": round(ds[int(len(ds) * 0.9)], 1),
        "max": round(ds[-1], 1),
    }


def basin_label(lat: float) -> str:
    for min_lat, label in BASIN_BANDS:
        if lat > min_lat:
            return label
    return "unknown"


